/**
 * 개발자: 박승우
 * 일자: 2026-08-05
 * 코멘트:
 *   1) 화면이 직접 만든 삭제 확인 문구에 참조 안내 한 줄을 덧붙인다
 *   2) deleteConfirm 대신 맞춤 문구를 쓰는 화면에서 호출한다
 *   3) 이미 같은 안내가 있으면 원문을 그대로 반환한다 — 두 번 붙지 않는다
 */
export function withDeleteRefHint(
  // 화면이 만든 확인 문구 — 여러 줄이어도 된다
  message: string
): string {
  const hint = "다른 자료에서 사용 중이면 삭제되지 않습니다.";
  if (message.includes(hint)) return message;
  return `${message}\n${hint}`;
}
