--  코멘트:
--    1) 공통코드 조회 SP를 co_cd = p_co_cd 완전 고유 격리로 바꾸기 전에 반드시 먼저 실행한다
--       (72에서 IN (p_co_cd, '0000') 상속을 제거하므로, 실물 복제가 없으면 전 화면 콤보가 즉시 빈다)
--    2) 복제 로직 자체는 13_sp_platform.sql의 sp_tbl_company_code_copy_c_000 정본을 그대로 호출한다
--       따라서 이 파일보다 13을 먼저 재적용해야 한다
--    3) 업체가 이미 가진 (main_cd, sub_cd)는 건드리지 않는다 — 몇 번 실행해도 결과가 같다
-- ============================================================

SET search_path TO sasshaccp;

-- ------------------------------------------------------------
-- 1. 사용 중인 전 업체에 표준코드 미보유분 복제
--    0000은 원본이므로 대상에서 뺀다
-- ------------------------------------------------------------
DO $$
DECLARE
    v_co record;
BEGIN
    FOR v_co IN
        SELECT co_cd FROM tbl_company WHERE co_cd <> '0000' ORDER BY co_cd
    LOOP
        CALL sp_tbl_company_code_copy_c_000(v_co.co_cd, 'system');
        RAISE NOTICE '표준코드 복제 완료 — co_cd=%', v_co.co_cd;
    END LOOP;
END$$;

-- ------------------------------------------------------------
-- 2. 검증용 — 업체별 코드 보유 수. 0000 건수 이상이어야 정상이다
-- ------------------------------------------------------------
SELECT co_cd, count(*) AS code_cnt
  FROM tbl_code
 GROUP BY co_cd
 ORDER BY co_cd;
